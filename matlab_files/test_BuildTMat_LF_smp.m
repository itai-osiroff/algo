
lambda=0.5;
x_stp=lambda/2; %this is the spacing between points on the image we generate


x_max=95;u_x_max=30;  %x_max is the width of the aberration layer we sample, u_x_max is the width of the speckle image we eventually generate (smaller than the actual aberration)


z_max=100; z_grid=[100];z_abrr=100; %in this simulation there is a single aberration layer and the aberration layer is 100um away from the fluorescent sources (i.e. the neuron)




Nm=length(z_grid);


OD=30;
sigt=1/(z_max/OD);

zin= [0];


Nz=length(zin);
Nx=u_x_max/x_stp*2+1;
Nxw=x_max/x_stp*2+1;
N=Nx^2;
hN=ceil(N/2);
hNx=ceil(Nx/2);


smp_stp=4;
Na=7;
lf_frq_res=1/Na;

%eventually we build a LF at a lower resolution, this is the sampling grid.
smp_inds_v_grid=smpctr(Nx,smp_stp);
Nx_smp=length(smp_inds_v_grid);
N_smp=Nx_smp^2;

%some simple shape for the neuron (i.e. points were we have emission), in this case just 3x3 dots
% We will build below only 9 columns of the transmission matrix, not all of
% them
smp_inds_i_grid=smpctr(Nx,smp_stp*12,3);
Nx_i_smp=length(smp_inds_i_grid);
neuronShape=zeros(Nx,Nx,'gpuArray');
neuronShape(smp_inds_i_grid,smp_inds_i_grid)=1;




neuron_inds=find(neuronShape);
Nl=length(neuron_inds(:));

zinL=zin*ones(1,Nl,'gpuArray');

uin=zeros(N,Nl,'gpuArray');
for j=1:Nl
uin(neuron_inds(j),j)=1;
end




%This function samples an aberration layer and generate an NxNl matrix u_out_t_hr
%Each collumn is a vectorization of the (Nx)x(Nx) complex speckle image
%generated by one fluorescent spot at a position defined by neuronShape
%It also generates a matrix u_out_t_LF of size N_smp^2xNlxNa^2  this is
%already the complex light field for each illuminatio. u_out_t_LF(:,j,:) is
%the light field for illumination j. It is now sampled in a low resolution
%of (N_smp)x(N_smp) instead of (Nx)x(Nx), but has NaxNa viewpoints.
%The function also return the aberration layer, and new, also the slopes of
%the aberration
blr_w=20*x_stp; scl_p=0.05;scl_p=0.1;
blr_w=40*x_stp;
%blr_w=80*x_stp; scl_p=0.05;

[u_out_t_LF,u_out_t_hr,maskL,mask_s, lf_ang_grid]=getLayerd_To_LF_and_hr(sigt,x_max,x_stp,z_max,lambda,blr_w,scl_p,uin,u_x_max,zinL,z_grid,1/Na,smp_stp);

LF1=reshape(abs(u_out_t_LF(:,ceil(Nl/2),:)).^2,[Nx_smp,Nx_smp,Na,Na]);
LF9=reshape(sum(abs(u_out_t_LF).^2,2),[Nx_smp,Nx_smp,Na,Na]);

displayLF(LF1,1); title('light field 1 bead')
displayLF(LF9,1); title('light field 9 beads')
im_1_LF=mean(mean(LF1,3),4);
im_9_LF=mean(mean(LF9,3),4);

figure, imagesc(im_1_LF); title('mean LF 1 bead')
figure, imagesc(im_9_LF); title('mean LF 9 beads')

im1_spk=reshape(abs(u_out_t_hr(:,ceil(Nl/2))).^2,[Nx,Nx]);
im9_spk=reshape(sum(abs(u_out_t_hr).^2,2),[Nx,Nx]);

figure, imagesc(im1_spk); title('spk img full apt 1 bead')
figure, imagesc(im9_spk); title('spk img full apt 9 beads')
